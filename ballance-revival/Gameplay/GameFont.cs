    public bool Ready => _tex.Id != 0;

    public GameFont(string texturePath)
    {
        if (!BallanceRevival.Rendering.ImageDecoder.TryLoad(texturePath, out Image img))
            return;
        _tex = Raylib.LoadTextureFromImage(img);
        Raylib.UnloadImage(img);
        if (_tex.Id != 0)
            Raylib.SetTextureFilter(_tex, TextureFilter.Bilinear);
    }

    public float Measure(string text, float height)
    {
        float scale = height / 32f;
        float w = 0f;
        foreach (char ch in text)
            w += Advance(ch) * scale;
        return w;
    }

    public void Draw(string text, float x, float y, float height, Color color)
    {
        if (_tex.Id == 0) return;
        float scale = height / 32f;
        float pen = x;
        foreach (char ch in text)
        {
            int i = Glyph(ch);
            float u = _g[i];
            float v = _g[i + 1];
            float gw = _g[i + 2];
            float pre = _g[i + 3];
            float post = _g[i + 4];
            float gh = _g[i + 5];
            if (gw > 0f && gh > 0f)
            {
                var src = new Rectangle(u, v, gw, gh);
                var dest = new Rectangle(pen + pre * scale, y, gw * scale, gh * scale);
                Raylib.DrawTexturePro(_tex, src, dest, Vector2.Zero, 0f, color);
            }
            pen += (pre + gw + post) * scale;
        }
    }

    public void DrawCentered(string text, float cx, float y, float height, Color color)
    {
        Draw(text, cx - Measure(text, height) / 2f, y, height, color);
    }

    private int Glyph(char ch)
    {
        int c = ch;
        if (c < 0 || c > 254) c = 32;
        return c * 6;
    }

    private float Advance(char ch)
    {
        int i = Glyph(ch);
        return _g[i + 2] + _g[i + 3] + _g[i + 4];
    }

    public void Dispose()
    {
        if (_tex.Id != 0) Raylib.UnloadTexture(_tex);
    }
